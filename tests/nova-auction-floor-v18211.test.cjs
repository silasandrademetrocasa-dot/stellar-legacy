const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const src=fs.readFileSync(require('node:path').join(__dirname,'../public/game.js'),'utf8');
const start=src.indexOf('function auctionSeed('),stop=src.indexOf('function auctionCurrentBid(');
assert(start>0&&stop>start);
const scope={Math,Date,Number,String,console,progress:{auction:{hourKey:'2026-10-11-23'}},ITEMS:{flax:{price:10000000},iris:{price:15000}},liveCatalog:(key)=>key==='drone:flax'?{price:10000000}:null,auctionHourKey:()=> '2026-10-11-23'};
vm.createContext(scope);vm.runInContext(src.slice(start,stop),scope);
const lot={ref:'item:iris',id:'iris',kind:'item',uri:15000};
const newLot=scope.normalizeAuctionEconomy({...lot},'2026-10-11-23');
assert.equal(newLot.reserve,100000000,'nova first bid 100m');
assert(newLot.finalSystemBid>newLot.reserve,'nova progression');
const ancient={...lot,reserve:900000,finalSystemBid:2400000,userBid:300000,marketBid:2000000};
const upgraded=scope.normalizeAuctionEconomy(ancient,'2026-10-11-23');
assert.equal(upgraded.reserve,100000000,'legacy reserve corrected');
assert.equal(upgraded.marketBid,2000000,'real standing bid retained');
const other=scope.normalizeAuctionEconomy({ref:'ammo:mcb50',uri:5000},'2026-10-11-23');
assert(other.reserve<100000000,'other lots not inflated');
scope.liveCatalog=(key)=>key==='drone:flax'?{price:12000000}:null;
assert.equal(scope.auctionNovaStartFloor(),100000000,'fixed nova floor independent of halo' );
assert.equal(scope.normalizeAuctionEconomy(upgraded,'2026-10-11-23').reserve,100000000);
console.log('PASS auction: Nova reserve fixed 100M, legacy correction and live bid preservation, other lots unaffected');
