import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.join(path.dirname(fileURLToPath(import.meta.url)),'..');
const js=fs.readFileSync(path.join(root,'public/game.js'),'utf8');
const pick=(start,end)=>{
  const a=js.indexOf(`function ${start}(`),b=js.indexOf(`function ${end}(`,a);
  assert(a>=0&&b>a,`not found ${start} → ${end}`);
  return js.slice(a,b);
};
assert(js.includes("img=new Image();img.decoding='async';img.loading='eager';"),'Canvas sprites must request downloads');
assert(!js.includes("img.loading=priority?'eager':'lazy'"),'Unattached lazy images cause BOX fallback forever');
assert(js.includes("/\\/assets\\/v18\\/bonus\\//.test(value)"),'Bonus asset should be cache-protected');
assert(js.includes('drawLocalShipVitals(p,shipSize);'),'local vitals must render even with HUD folded');
const calls=[];
const ctx={save(){},restore(){},fillRect(...args){calls.push({kind:'fill',color:this.fillStyle,args});}};
const context={ctx,player:{hp:200,maxHp:400,shield:30,maxShield:100},Math,Number};
vm.runInNewContext(pick('drawLocalShipVitals','drawPlayer'),context);
context.drawLocalShipVitals({x:100,y:130},80);
assert.equal(calls.length,4);
assert.equal(calls[1].color,'#ff566d');
assert.equal(calls[3].color,'#49cfff');
assert(Math.abs(calls[1].args[2]-calls[0].args[2]/2)<1e-6,'HP is 50%');
assert(Math.abs(calls[3].args[2]-calls[2].args[2]*.3)<1e-6,'Shield is 30%');
calls.length=0;
context.player.hp=-100;context.player.shield=1000;
context.drawLocalShipVitals({x:100,y:130},80);
assert.equal(calls[1].args[2],0,'HP should clamp to zero');
assert.equal(calls[3].args[2],calls[2].args[2],'shield should clamp to max width');
// BOX fallback no longer draws a cyan square, and real WEBP path uses ctx.drawImage.
const ops=[];
const drawCtx={save(){},restore(){},translate(){},drawImage(){ops.push('image');},fillRect(){ops.push('square');},strokeRect(){ops.push('square-stroke');},beginPath(){},moveTo(){},lineTo(){},closePath(){},fill(){ops.push('poly');},stroke(){},arc(){}};
const bctx={ctx:drawCtx,bonusBoxTargetForMap:()=>20,assetImage:()=>({naturalWidth:144}),GAME_ASSETS:{bonus:{box:'/assets/v18/bonus/bonus-box.webp'}},resolvedQualityMode:()=> 'low',state:{bonusBoxes:[{x:5,y:5}]},onScreenWorld:()=>true,screenPos:()=>({x:10,y:10}),nowSec:()=>0,Math,TWO_PI:2*Math.PI};
vm.runInNewContext(pick('drawBonusBoxes','createOres'),bctx);
bctx.drawBonusBoxes();assert.deepEqual(ops,['image']);
ops.length=0;bctx.assetImage=()=>null;bctx.drawBonusBoxes();assert(ops.includes('poly')&&!ops.includes('square')&&!ops.includes('square-stroke'),'fallback must be geometric not square');
for(const f of ['bonus-box.webp','stellar-dust.webp']){const data=fs.readFileSync(path.join(root,'public/assets/v18/bonus',f));assert.equal(data.toString('ascii',0,4),'RIFF');assert.equal(data.toString('ascii',8,12),'WEBP');assert(data.length<20000,'stay light');}
console.log('✅ V18.2.8 • Sprite carregável, fallback geométrico, HP/ESC reagindo e cache protegido — PASS');
